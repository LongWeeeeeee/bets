#!/bin/bash
# Ночной добор свежих про-карт в корпус. Идёт ПЕРЕД пересборкой снимка.
#
# Зачем. Пересборка снимка (05:30) приводит снимок к тому корпусу, который лежит
# на диске, и сама корпус не наполняет — это записано в её собственной шапке.
# Наполнение до 18.08.2026 держалось на ручных запусках, а когда снежный ком по
# командам исчерпался, `get_pros()` начал молча возвращать «опрошено 0».
# Корпус застыл на 12.08 и обнаружилось это только по возрасту снимка.
#
# Почему 04:30. За час до пересборки: снимок должен собираться уже на
# пополненном корпусе, иначе свежие карты доедут до прода лишь через сутки.
# Часа хватает с запасом — добор идёт около 15 минут, из них большая часть это
# два обхода корпуса ради списка команд.
#
# Отдельной джобой, а не шагом пересборки: если добор упадёт (протухли ключи
# Stratz, лёг прокси), пересборка всё равно обязана отработать на том корпусе,
# что есть, и предупредить о его возрасте своей проверкой. Сцепив их, мы бы
# теряли и снимок тоже.
set -e
cd /Users/alex/Documents/ingame
PY=venv_catboost/bin/python3
LOG="runtime/pro_topup_$(date +%Y%m%d_%H%M).log"

run_topup() {
  $PY runtime/experiments/misc/topup_pro_corpus.py
}

# Под launchd работать НАДО В ПЕРЕДНЕМ ПЛАНЕ: уйдя в фон и выйдя, скрипт
# сообщит launchd о завершении, и тот убьёт всю группу процессов. В терминале
# наоборот удобнее фон. Та же развилка, что в rebuild_prematch_snapshot.sh.
if [ -t 1 ]; then
  run_topup > "$LOG" 2>&1 &
  PID=$!
  echo "$PID" > runtime/pro_topup.pid
  echo "добор запущен в фоне, PID $PID"
  echo "лог: $LOG"
else
  run_topup > "$LOG" 2>&1
fi
