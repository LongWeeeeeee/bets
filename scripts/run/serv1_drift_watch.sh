#!/bin/bash
# Ежедневный сторож расхождений: боевой код serv1 против репозитория.
#
# Зачем. Репозиторий и прод разошлись форком, а не отставанием (аудит
# 19.08.2026): каждая сторона содержит то, чего нет у другой. Четыреста строк
# ядра расчёта существовали в единственном экземпляре на одной машине.
#
# Почему НЕ автосинхронизация. `git pull` на serv1 не упал бы, а тихо подменил
# гибридную предматчевую модель (AUC ~0.72) чистым драфтом (~0.61) и затёр бы
# `id_to_names.py`, который дописывает сам боевой процесс. Выравнивание тут —
# автоматизация аварии. Сторож только СМОТРИТ: на serv1 не пишет ничего.
#
# Почему 05:00. Между добором корпуса (04:30) и пересборкой снимка (05:30):
# работа занимает около минуты и никому не мешает.
#
# Что делает: тянет .py с serv1, кладёт в ветку serv1-prod-snapshot, печатает
# что изменилось с прошлого раза. Секреты (keys.py и бэкапы) исключаются, и это
# проверяется ФАКТОМ после копирования, а не доверием к правилам rsync.
set -e
cd /Users/alex/Documents/ingame
PY=venv_catboost/bin/python3
LOG="runtime/serv1_drift_$(date +%Y%m%d_%H%M).log"

run_watch() {
  $PY runtime/experiments/cyberscore-prod/serv1_drift_watch.py
}

# Под launchd работать НАДО В ПЕРЕДНЕМ ПЛАНЕ: уйдя в фон и выйдя, скрипт
# сообщит launchd о завершении, и тот убьёт группу процессов. Та же развилка,
# что в rebuild_prematch_snapshot.sh и topup_pro_corpus.sh.
if [ -t 1 ]; then
  run_watch > "$LOG" 2>&1 &
  echo "$!" > runtime/serv1_drift.pid
  echo "сторож запущен в фоне, лог: $LOG"
else
  run_watch > "$LOG" 2>&1
fi
